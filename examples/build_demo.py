# -*- coding: utf-8 -*-
"""示例：用 chalco_deck 版式库生成一份「公司简介」风格的演示文稿。

文中所有公司名、数字、项目名均为占位示例，替换成自己的内容即可。
输出写到**当前工作目录**的 demo/ 下（不写进技能目录，保持技能只读）。

    python examples/build_demo.py        # 输出 ./demo/示例-公司简介.pptx
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "scripts"))

from chalco_deck import C, Deck, asset  # noqa: E402

OUT = Path.cwd() / "demo" / "示例-公司简介.pptx"

d = Deck()

# --------------------------------------------------------------------- 01 封面
d.cover(
    title="公司简介",
    subtitle="环境服务 · 绿色发展",
    en="EXAMPLE ENVIRONMENTAL GROUP",
    location="中国 · 北京",
    date="2026.10",
)

# --------------------------------------------------------------------- 02 目录
d.toc(
    [
        ("公司简介", "COMPANY PROFILE"),
        ("科技立企", "TECHNOLOGY"),
        ("业务能力", "CAPABILITY"),
        ("商业模式", "BUSINESS MODEL"),
    ],
    subtitle="专注环保节能领域的\n专业技术与服务平台",
)

# --------------------------------------------------------------- 03 章节页
d.section("01", "公司简介", en="COMPANY PROFILE", photo=asset("photo_leaf.jpg"),
          caption="2018 年成立于北京，注册资本 5 亿元（示例数据）")

# --------------------------------------------------------- 04 概况：图 + 要点
p = d.page("公司概况")
p.bullets(
    [
        [("2018 年", {"color": C.GREEN, "bold": True}), "成立于北京，注册资本 5 亿元人民币。"],
        "聚焦工业环保节能，形成「技术 + 工程 + 运营」一体化服务能力。",
        [("三大板块", {"color": C.GREEN, "bold": True}), "覆盖环保工程、节能服务、运营服务。"],
        "服务有色金属、钢铁、化工等行业客户，业务覆盖 10 余个省市。",
        "坚持自主研发与产学研合作，形成可复制的行业解决方案。",
    ],
    box=(0.95, 1.45, 6.55, 4.15),
    size=15,
    line_spacing=1.45,
    space_after=12,
)
p.image(asset("photo_leaf.jpg"), box=(7.95, 1.45, 4.43, 4.15), radius=0.14)
p.note(
    [[("示例说明  ", {"bold": True, "color": C.GREEN}),
      "本页文字与数字均为占位示例，正式使用前请替换为经审核的内容。"]],
    box=(0.95, 5.85, 11.43, 0.55),
)

# ------------------------------------------------------------- 05 关键指标
p = d.page("关键指标")
p.kpis(
    [
        ("5", "亿元", "注册资本，2018 年设立"),
        ("32", "家", "所属企业与合作单位"),
        ("1.2", "亿元", "累计科研投入"),
        ("86", "项", "专利授权与软件著作权"),
    ],
    box=(0.95, 1.40, 11.43, 1.95),
)
p.table(
    ["业务板块", "核心内容", "代表能力"],
    [
        ["环保工程", "烟气治理、废水处理、固废资源化", "EPC / 设计 / 调试"],
        ["节能服务", "余热利用、能效诊断、合同能源管理", "EMC / 节能改造"],
        ["运营服务", "水务运营、检测监测、环保管家", "长期托管运营"],
        ["科技研发", "资源化利用、危废处置、碳资产", "标准编制 / 技术转化"],
    ],
    box=(0.95, 3.60, 11.43, 2.55),
    col_widths=[2.0, 5.4, 3.4],
    size=12.5,
)

# ------------------------------------------------------------- 06 三卡阵列
p = d.page("企业文化")
p.cards(
    [
        dict(title="核心价值观", lines=["创新  共赢", "诚信  责任"],
             image=asset("bg_section.jpg")),
        dict(title="经营宗旨", lines=["产业生态化", "生态产业化"],
             image=asset("photo_leaf.jpg")),
        dict(title="使  命", lines=["让环境更美好", "让发展更绿色"],
             image=asset("bg_cover_full.jpg")),
    ],
    box=(0.95, 1.40, 11.43, 4.95),
    gap=0.34,
    image_h=2.30,
)

# ------------------------------------------------------------- 07 表格 + 标签
p = d.page("业务能力")
p.text([[("覆盖环保节能全链条的服务能力", {"size": 20, "bold": True})]],
       box=(0.95, 1.35, 11.43, 0.45))
p.tags(["烟气治理", "废水处理", "固废资源化", "余热利用", "检测监测", "环保管家"],
       box=(0.95, 1.92), size=13, h=0.38)
p.table(
    ["能力", "说明", "典型场景"],
    [
        ["技术研发", "1 个技术中心 + 多个联合实验室，CNAS 认可实验室", "工艺包开发、中试"],
        ["工程设计", "拥有环保工程设计与总承包资质", "烟气净化改造"],
        ["运营服务", "覆盖 10 余个省市的运营网络", "水务、检测、环保管家"],
        ["标准编制", "主导 / 参与国家、行业、团体标准 10 余项", "资源化利用标准"],
    ],
    box=(0.95, 2.55, 11.43, 3.55),
    col_widths=[2.0, 6.6, 3.2],
    size=12.5,
)

# ----------------------------------------------------------- 08 流程 + 时间线
p = d.page("发展历程")
p.process(
    [("2018", "公司成立"), ("2019", "区域布局"), ("2021", "业务扩张"),
     ("2023", "技术中心"), ("2026", "生态构建")],
    box=(0.95, 1.42, 11.43, 0.86),
)
p.timeline(
    [
        ("2019.01", "首个区域公司", "区域业务落地"),
        ("2019.08", "资源化项目", "固废资源利用"),
        ("2021.04", "区域分公司", "业务半径扩大"),
        ("2023.04", "技术中心", "科技研发、技术服务"),
    ],
    box=(0.95, 2.62, 5.6, 3.55),
    size=12.5,
)
p.image(asset("bg_cover_full.jpg"), box=(6.85, 2.62, 5.53, 3.55), radius=0.14)

# --------------------------------------------------------- 09 商业模式
p = d.page("商业模式")
p.text([[("以技术为核心，构建「投、建、运」一体化商业模式", {"size": 20, "bold": True})]],
       box=(0.95, 1.35, 11.43, 0.45))
p.process(
    [("技术研发", "标准与专利"), ("工程总包", "EPC 交付"),
     ("投资运营", "长期收益"), ("数据服务", "价值挖掘")],
    box=(0.95, 1.95, 11.43, 1.05),
    title_size=15,
    text_size=11,
)
p.banner("示例集团「三大板块」发展战略", box=(0.95, 3.35, 11.43, 0.52))
p.cards(
    [
        dict(title="工程板块", lines=["设计", "总包", "调试"]),
        dict(title="运营板块", lines=["水务", "检测", "环保管家"]),
        dict(title="新兴板块", lines=["资源化", "碳资产", "智慧运维"]),
    ],
    box=(0.95, 4.10, 11.43, 2.05),
    gap=0.34,
    title_size=16,
    body_size=13,
)
p.note(
    [[("说明  ", {"bold": True, "color": C.GREEN}),
      "示例内容仅用于展示版式，正式使用前请替换为经审核的数据与表述。"]],
    box=(0.95, 6.32, 11.43, 0.45),
    size=12,
)

# --------------------------------------------------------------- 10 结尾页
d.closing()

path = d.save(OUT)
print("wrote", path)
